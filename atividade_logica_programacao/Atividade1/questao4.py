#Explicação Linha por Linha com os valores das variáveis em cada etapa da execução sequencial:

#A = 8
#A variável A é criada e recebe o valor 8. Neste momento, B ainda não existe.
#B = 4
#A variável B é criada e recebe o valor 4. Agora, temos A = 8 e B = 4.
#A = B
#A variável A recebe o valor que está guardado em B neste exato momento. Como B vale 4, o valor antigo de A (que era 8) é apagado e A passa a valer 4. Agora, ambas as variáveis valem 4.
#B = A + 5
#A variável B recebe o valor atual de A somado a 5. Como A agora vale 4, o cálculo feito é \ (4 + 5 = 9\). O valor antigo de B é substituído, e B passa a valer 9.
